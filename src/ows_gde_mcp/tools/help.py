"""MCP tools for the OWS knowledge vault — local Obsidian vault, no network.

The knowledge lives in an **Obsidian-standard vault** at `docs/help/vault/`:

    docs/help/vault/
        Home.md                  MOC top node (git-tracked)
        00 Findings/*.md         human-curated, evolving findings (git-tracked)
        Reference/<nav tree>/*.md auto-generated OWS help corpus (gitignored)
    docs/help/index/<lang>/
        nav_index.json           flat [{id, parent_id, name, local, depth, path}]
        topics.jsonl             [{id, name, local, title, text}] fast-search sidecar

Two layers, two lifecycles:

- **Reference/** is the ~3.6k-page OWS help corpus, regenerated by
  `scripts/import_help_corpus.py` (copied verbatim from the scraped vault so
  it stays Obsidian-navigable). It is gitignored — regenerable, not shipped.
- **00 Findings/** + **Home.md** are hand-curated and git-tracked. Anyone can
  add a findings note; the importer never touches them.

These tools make **findings the first thing an agent reads**: `get_help_home`
returns the MOC, and `search_help` ranks `00 Findings/` hits above the raw
Reference corpus — so a curated summary short-circuits a full-corpus search.

This file makes NO live network calls. If the cache is missing the tools return
a structured `error.no_cache` telling the caller how to populate it.
"""

from __future__ import annotations

import json
import os
import re
from html.parser import HTMLParser
from pathlib import Path
from typing import Any

from ows_gde_mcp.config import settings as _settings

# Curated, git-tracked parts of the vault.
_FINDINGS_DIR = "00 Findings"
_HOME_FILE = "Home.md"

# Default language. The Reference corpus is currently en_US only.
_DEFAULT_LANG = "en_US"


def _vault_root() -> Path:
    """Resolve the knowledge-vault directory (writable, per-project by default).

    Resolution order:
      1. ``OWS_VAULT_DIR`` — from `.env` (Settings) or the environment.
      2. ``<cwd>/ows-vault`` — per-project default.

    Resolved per call so the location can change at runtime and so the env var
    (set by the plugin, the user's shell, or a test) always wins. Findings the
    end user adds live here; the importer writes ``Reference/`` and the search
    index here too.
    """
    # Live env wins (plugin / shell / test override); then .env via Settings.
    configured = os.environ.get("OWS_VAULT_DIR") or _settings.OWS_VAULT_DIR
    if configured:
        return Path(configured).expanduser()
    return Path.cwd() / "ows-vault"


def _index_dir(lang: str = _DEFAULT_LANG) -> Path:
    # Hidden, gitignored sidecar search index inside the vault dir.
    return _vault_root() / ".index" / lang


def _findings_dir() -> Path:
    return _vault_root() / _FINDINGS_DIR


def _no_cache_error(lang: str) -> dict[str, Any]:
    return {
        "error": {
            "code": "no_cache",
            "message": (
                f"Help index for {lang!r} is empty at {_index_dir(lang)} and no "
                f"findings exist at {_findings_dir()}. Populate the Reference "
                "corpus with `uv run python scripts/import_help_corpus.py "
                "--vault ~/codes/huaweed/knowledge-helper/vault`, and/or add a "
                f"note under '{_FINDINGS_DIR}/'."
            ),
        }
    }


def _load_index(lang: str) -> list[dict] | None:
    path = _index_dir(lang) / "nav_index.json"
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


# ---------------- HTML extraction (legacy fetch_help_docs.py output) ----------


class _TopicTextExtractor(HTMLParser):
    """Pull title + plain text from a legacy OWS help topic HTML page.

    Only used for `.html` topics produced by `scripts/fetch_help_docs.py`. The
    vault Reference corpus is Markdown, which is served as-is.
    """

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self._buf: list[str] = []
        self._stack: list[str] = []
        self._title: str | None = None
        self._in_title = False
        self._suppress = 0  # >0 inside <script>/<style>
        self._block_tags = {
            "p", "li", "h1", "h2", "h3", "h4", "h5", "h6",
            "br", "tr", "td", "th", "div", "ul", "ol",
        }
        self._parent_topic: tuple[str, str] | None = None
        self._in_parentlink = False
        self._link_target: str | None = None

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        self._stack.append(tag)
        attrs_d = dict(attrs)
        if tag == "script" or tag == "style":
            self._suppress += 1
            return
        if tag == "h1" and "topictitle1" in (attrs_d.get("class") or ""):
            self._in_title = True
        if tag == "div" and "parentlink" in (attrs_d.get("class") or ""):
            self._in_parentlink = True
        if tag == "a" and self._in_parentlink:
            self._link_target = attrs_d.get("href")

    def handle_endtag(self, tag: str) -> None:
        if (tag == "script" or tag == "style") and self._suppress > 0:
            self._suppress -= 1
        if tag == "h1":
            self._in_title = False
        if tag == "div" and self._in_parentlink:
            self._in_parentlink = False
        if tag in self._block_tags:
            self._buf.append("\n")
        if self._stack and self._stack[-1] == tag:
            self._stack.pop()

    def handle_data(self, data: str) -> None:
        if self._suppress:
            return
        if self._in_title:
            self._title = (self._title or "") + data
            return
        if self._in_parentlink and self._link_target and data.strip():
            self._parent_topic = (data.strip(), self._link_target)
            self._link_target = None
        self._buf.append(data)

    @property
    def title(self) -> str | None:
        return self._title.strip() if self._title else None

    @property
    def text(self) -> str:
        joined = "".join(self._buf)
        return re.sub(r"\n{3,}", "\n\n", joined).strip()

    @property
    def parent_topic(self) -> dict[str, str] | None:
        if not self._parent_topic:
            return None
        name, href = self._parent_topic
        return {"name": name, "local": href}


def _extract_topic_body(html: str) -> tuple[str | None, str, dict | None]:
    p = _TopicTextExtractor()
    p.feed(html)
    return p.title, p.text, p.parent_topic


def _md_title(raw: str) -> str | None:
    """First ATX heading (`# ...`) of a markdown body, else None."""
    for line in raw.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return None


